/// <reference types="node" />
/**
 * Generates the two files NativeWind needs from the TypeScript theme (single source of truth):
 *   src/global.css                 – CSS variables for Light and Night (rgb channels so `bg-primary/50` works)
 *   src/theme/tailwind.generated.js – colour/font-size/radius maps for tailwind.config.js
 * Run after editing anything in src/theme:  npm run theme:sync   (then restart Metro with --clear)
 */
import { writeFileSync } from 'node:fs';

import { extras, palettes, type Scheme } from '../src/theme/colors';
import { radius } from '../src/theme/radius';
import { toTokens } from '../src/theme/tokens';
import { families, typography } from '../src/theme/typography';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const channels = (hex: string) => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};
const isHex = (v: string) => /^#[0-9A-Fa-f]{6}$/.test(v);

/** Every opaque colour as { cssVarName: "r g b" } for one scheme. */
function varsFor(scheme: Scheme) {
  const p = palettes[scheme];
  const e = extras[scheme];
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(p)) if (isHex(v)) out[kebab(k)] = channels(v);
  out['on-leaf'] = channels(e.onLeaf);
  out['on-danger'] = channels(e.onDanger);
  for (const [k, v] of Object.entries(toTokens(p, e))) out[kebab(k)] = channels(v);
  out['popover-foreground'] = channels(p.ink);
  return out;
}

const block = (selector: string, vars: Record<string, string>) =>
  `  ${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `    --${k}: ${v};`)
    .join('\n')}\n  }`;

const css = `@tailwind base;
@tailwind components;
@tailwind utilities;

/* GENERATED by scripts/sync-theme.ts from src/theme/*.ts – do not edit by hand. */
@layer base {
${block(':root', varsFor('light'))}

${block('.dark:root', varsFor('night'))}
}
`;
writeFileSync('src/global.css', css);

// ── tailwind.generated.js ────────────────────────────────────────────────
const colorNames = Object.keys(varsFor('light'));
const colors: Record<string, string> = {};
for (const n of colorNames) colors[n] = `rgb(var(--${n}) / <alpha-value>)`;

const fontSize: Record<string, [string, Record<string, string>]> = {};
for (const [name, s] of Object.entries(typography)) {
  fontSize[`kz-${kebab(name)}`] = [
    `${s.size}px`,
    {
      lineHeight: `${s.lineHeight}px`,
      ...('letterSpacing' in s && s.letterSpacing ? { letterSpacing: `${s.letterSpacing}px` } : {}),
    },
  ];
}

const fontFamily = {
  display: [families.display['600']],
  'display-medium': [families.display['500']],
  sans: [families.sans['400']],
  'sans-medium': [families.sans['500']],
  'sans-semibold': [families.sans['600']],
  'sans-bold': [families.sans['700']],
};

// Radii: sm→lg are inputs (12); xl/2xl/3xl/card are cards (20); hero is 28; full/pill are round.
const borderRadius = {
  none: '0px',
  sm: `${radius.input}px`,
  DEFAULT: `${radius.input}px`,
  md: `${radius.input}px`,
  lg: `${radius.input}px`,
  xl: `${radius.input}px`,
  '2xl': `${radius.card}px`,
  '3xl': `${radius.card}px`,
  card: `${radius.card}px`,
  hero: `${radius.hero}px`,
  pill: `${radius.pill}px`,
  full: '9999px',
};

writeFileSync(
  'src/theme/tailwind.generated.js',
  `// GENERATED by scripts/sync-theme.ts – do not edit by hand.\nmodule.exports = ${JSON.stringify({ colors, fontSize, fontFamily, borderRadius }, null, 2)};\n`
);
console.log('theme synced:', colorNames.length, 'colours,', Object.keys(fontSize).length, 'type styles');

const REVIEW = { name: 'Reviewer name (placeholder)', role: 'Certified yoga teacher', date: '2026-01-15' };
const MEDIA = { type: 'placeholder' as const, uri: null, rights: 'placeholder – no third-party asset' };

interface Def {
  name: string;
  alt: string | null;
  cat: ExerciseCategory;
  lvl?: Level;
  dur: number;
  reps?: number | null;
  side?: Side;
  pos: Position;
  goal: Goal[];
  int?: Intensity;
  acc?: AccessibilityTag[];
  eq?: Equipment[];
  props?: string[];
  setup: string;
  steps: string[];
  cues: string[];
  exit: string;
  mistakes: string[];
  mods: [Modification['kind'], string, string][];
  cautions: string[];
}

const STOP = 'Stop if you feel sharp pain or dizziness.';

function E(n: number, d: Def): Exercise {
  return {
    id: `ex-${String(n).padStart(2, '0')}`,
    name: d.name,
    altName: d.alt,
    category: d.cat,
    level: d.lvl ?? 'beginner',
    durationSec: d.dur,
    reps: d.reps ?? null,
    side: d.side ?? 'none',
    steps: d.steps,
    breathingCues: d.cues,
    setup: d.setup,
    safeExit: d.exit,
    commonMistakes: d.mistakes,
    modifications: d.mods.map(([kind, title, text]) => ({ kind, title, text })),
    props: d.props ?? [],
    cautions: d.cautions,
    tags: {
      goal: d.goal,
      intensity: d.int ?? 'gentle',
      position: d.pos,
      accessibility: d.acc ?? [],
      equipment: d.eq ?? [],
    },
    media: MEDIA,
    review: REVIEW,
    version: 1,
  };
}

